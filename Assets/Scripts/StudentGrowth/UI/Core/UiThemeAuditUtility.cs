using System.Collections.Generic;
using System.Text;
using UnityEngine;
using UnityEngine.UI;

namespace StudentGrowth
{
    public sealed class UiThemeAuditSummary
    {
        public bool themeFound;
        public int themeSpriteChecks;
        public int buttonCount;
        public int panelCandidateCount;
        public int textCount;
        public int pixelTextCount;

        private readonly List<string> issues = new List<string>();

        public IReadOnlyList<string> Issues
        {
            get { return issues; }
        }

        public void AddIssue(string issue)
        {
            if (!string.IsNullOrEmpty(issue))
            {
                issues.Add(issue);
            }
        }

        public string BuildLog()
        {
            StringBuilder builder = new StringBuilder();
            builder.AppendLine("Student Growth UI Theme Audit");
            builder.AppendLine("Theme found: " + themeFound);
            builder.AppendLine("Theme sprite fields checked: " + themeSpriteChecks);
            builder.AppendLine("Buttons scanned: " + buttonCount);
            builder.AppendLine("Panel-like images scanned: " + panelCandidateCount);
            builder.AppendLine("Texts scanned: " + textCount);
            builder.AppendLine("Texts with PixelText: " + pixelTextCount);
            builder.AppendLine("Issues: " + issues.Count);

            for (int i = 0; i < issues.Count; i++)
            {
                builder.Append(i + 1);
                builder.Append(". ");
                builder.AppendLine(issues[i]);
            }

            return builder.ToString();
        }

        public string BuildMarkdown()
        {
            StringBuilder builder = new StringBuilder();
            builder.AppendLine("# Student Growth UI Theme Audit");
            builder.AppendLine();
            builder.AppendLine("Generated by `Tools/Student Growth/UI/Export Theme Audit Markdown`.");
            builder.AppendLine();
            builder.AppendLine("## Summary");
            builder.AppendLine();
            builder.AppendLine("| Metric | Value |");
            builder.AppendLine("| --- | ---: |");
            builder.AppendLine("| Theme found | " + (themeFound ? "Yes" : "No") + " |");
            builder.AppendLine("| Theme sprite fields checked | " + themeSpriteChecks + " |");
            builder.AppendLine("| Buttons scanned | " + buttonCount + " |");
            builder.AppendLine("| Panel-like images scanned | " + panelCandidateCount + " |");
            builder.AppendLine("| Texts scanned | " + textCount + " |");
            builder.AppendLine("| Texts with PixelText | " + pixelTextCount + " |");
            builder.AppendLine("| Issues | " + issues.Count + " |");
            builder.AppendLine();
            builder.AppendLine("## Issues");
            builder.AppendLine();
            if (issues.Count == 0)
            {
                builder.AppendLine("No issues found by the current audit rules.");
                return builder.ToString();
            }

            for (int i = 0; i < issues.Count; i++)
            {
                builder.Append(i + 1);
                builder.Append(". ");
                builder.AppendLine(issues[i]);
            }

            return builder.ToString();
        }
    }

    public static class UiThemeAuditUtility
    {
        public static void AuditUiRoot(UiThemeAuditSummary summary, GameObject root, string scope)
        {
            if (summary == null || root == null)
            {
                return;
            }

            Button[] buttons = root.GetComponentsInChildren<Button>(true);
            for (int i = 0; i < buttons.Length; i++)
            {
                AuditButton(summary, buttons[i], scope);
            }

            Image[] images = root.GetComponentsInChildren<Image>(true);
            for (int i = 0; i < images.Length; i++)
            {
                AuditPanelImage(summary, images[i], scope);
            }

            Text[] texts = root.GetComponentsInChildren<Text>(true);
            for (int i = 0; i < texts.Length; i++)
            {
                AuditText(summary, texts[i], scope);
            }
        }

        public static bool LooksLikePanel(string objectName)
        {
            if (string.IsNullOrEmpty(objectName))
            {
                return false;
            }

            string value = objectName.ToLowerInvariant();

            // 2026-10-28（T7）：进度条（EnergyBarBack / EnergyBarFill / PressureBarFill …）
            // 是纯色填充图，本来就不该挂 PixelPanel —— 挂上反而会被九宫格拉伸变形。
            // 原来 "bar" 一命中就要求 PixelPanel，每个场景都会报一串误报。
            if (IsProgressBar(value))
            {
                return false;
            }

            return value.Contains("panel")
                || value.Contains("window")
                || value.Contains("dialog")
                || value.Contains("prompt")
                || value.Contains("menu")
                || value.Contains("hud")
                || value.Contains("bar")
                || value.Contains("view");
        }

        /// <summary>条状填充图：名字里带 bar，且以 back / fill 结尾。</summary>
        private static bool IsProgressBar(string lowerName)
        {
            if (!lowerName.Contains("bar"))
            {
                return false;
            }

            return lowerName.EndsWith("back")
                || lowerName.EndsWith("fill")
                || lowerName.Contains("barback")
                || lowerName.Contains("barfill");
        }

        public static string GetHierarchyPath(Transform transform)
        {
            if (transform == null)
            {
                return string.Empty;
            }

            Stack<string> names = new Stack<string>();
            Transform current = transform;
            while (current != null)
            {
                names.Push(current.name);
                current = current.parent;
            }

            return string.Join("/", names.ToArray());
        }

        private static void AuditButton(UiThemeAuditSummary summary, Button button, string scope)
        {
            if (button == null)
            {
                return;
            }

            summary.buttonCount++;
            // 2026-10-28（T7）：Button_HitArea 这类纯点击热区没有可见底图，
            // 挂 PixelButton 反而会多画一层。名字里带 hitarea / hitbox 的直接放过。
            string lowerName = button.gameObject.name.ToLowerInvariant();
            if (lowerName.Contains("hitarea") || lowerName.Contains("hitbox"))
            {
                return;
            }

            if (button.GetComponent<PixelButton>() == null)
            {
                summary.AddIssue(scope + " button missing PixelButton: " + GetHierarchyPath(button.transform));
            }
        }

        private static void AuditPanelImage(UiThemeAuditSummary summary, Image image, string scope)
        {
            if (image == null || !LooksLikePanel(image.gameObject.name))
            {
                return;
            }

            summary.panelCandidateCount++;
            if (image.GetComponent<PixelPanel>() == null)
            {
                summary.AddIssue(scope + " panel-like image missing PixelPanel: " + GetHierarchyPath(image.transform));
            }
        }

        private static void AuditText(UiThemeAuditSummary summary, Text text, string scope)
        {
            if (text == null)
            {
                return;
            }

            summary.textCount++;
            if (text.GetComponent<PixelText>() != null)
            {
                summary.pixelTextCount++;
                return;
            }

            summary.AddIssue(scope + " text missing PixelText: " + GetHierarchyPath(text.transform));
        }
    }
}
